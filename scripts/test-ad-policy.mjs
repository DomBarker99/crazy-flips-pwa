import assert from "node:assert/strict";
import fs from "node:fs";
import vm from "node:vm";
import path from "node:path";
import {root} from "./release-lib.mjs";
const self={pwaState:{}};
vm.runInNewContext(fs.readFileSync(path.join(root,"app/offline-ads.js"),"utf8"),{self,setTimeout,Promise});
let initialized=0,originalRequests=0;
const sdk={async init(){initialized++;return "ready";},ad:{async requestAd(){originalRequests++;}}};
self.installOfflineAdPolicy(sdk);
self.installOfflineAdPolicy(sdk);
assert.equal(await sdk.init(),"ready");assert.equal(initialized,1);
const order=[];
const task=sdk.ad.requestAd("midgame",{adStarted(){order.push("started");},adFinished(){order.push("finished");}});
assert.deepEqual(order,[],"Callbacks must not fire before the game can attach its continuation");
await task;assert.deepEqual(order,["started","finished"]);assert.equal(originalRequests,0);
assert.equal(self.pwaState.completedAdRequests,1);
await sdk.ad.requestAd("rewarded",{adFinished(){order.push("reward-complete");}});
assert.equal(order.at(-1),"reward-complete");assert.equal(originalRequests,0);
await assert.rejects(sdk.ad.requestAd("midgame",{adStarted(){throw Error("callback test");}}),/callback test/);
console.log("PASS: silent asynchronous midgame/rewarded callbacks; original ad renderer never called");
